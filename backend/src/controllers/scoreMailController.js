import nodemailer from 'nodemailer'
import { jsPDF } from 'jspdf'

const env = process.env
const escape = value =>
  String(value ?? '').replace(/[&<>"']/g, c =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c])
  )

function buildScorePdfBuffer(exam, candidate, classAvg, totalCandidates) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const pct = candidate.total > 0 ? ((candidate.score / candidate.total) * 100).toFixed(1) : '0.0'
  const avgPct = candidate.total > 0 ? ((classAvg / candidate.total) * 100).toFixed(1) : '0.0'

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(18)
  doc.text('UnCooked — Official Score Report', 48, 60)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(11)
  doc.setTextColor(108, 106, 101)
  doc.text(`Examination: ${exam.title}`, 48, 88)
  if (exam.description) {
    doc.text(`Topics: ${String(exam.description).slice(0, 90)}`, 48, 106)
  }

  doc.setDrawColor(233, 233, 231)
  doc.line(48, 122, 547, 122)

  doc.setTextColor(55, 53, 47)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(13)
  doc.text(`Candidate: ${candidate.name}`, 48, 150)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(12)
  let y = 185
  const rows = [
    ['Your Score', `${candidate.score} / ${candidate.total} (${pct}%)`],
    ['Class Average', `${classAvg} / ${candidate.total} (${avgPct}%)`],
    ['Percentile', `${candidate.percentile ?? 0}%`],
    ['Rank', `${candidate.rank} / ${totalCandidates}`],
  ]

  for (const [label, val] of rows) {
    doc.setFont('helvetica', 'bold')
    doc.text(label + ':', 48, y)
    doc.setFont('helvetica', 'normal')
    doc.text(String(val), 180, y)
    y += 28
  }

  doc.setFontSize(9)
  doc.setTextColor(108, 106, 101)
  doc.text('Generated by UnCooked Secure Examination Management System', 48, 760)

  return Buffer.from(doc.output('arraybuffer'))
}

export async function sendScoreReports(req, res) {
  res.setHeader('Cache-Control', 'no-store')
  const token = req.headers.authorization?.match(/^Bearer (\S+)$/)?.[1]
  if (!token) return res.status(401).json({ error: 'Sign in to send score reports.' })

  const examId = req.body?.examId
  if (typeof examId !== 'string' || !/^[a-f0-9-]{36}$/i.test(examId))
    return res.status(400).json({ error: 'Provide a valid examination ID.' })

  if (
    !env.EMAIL_HOST ||
    !env.EMAIL_USER ||
    !env.EMAIL_PASS ||
    !env.SUPABASE_URL ||
    !env.SUPABASE_PUBLISHABLE_KEY
  ) {
    return res
      .status(503)
      .json({ error: 'Email delivery has not been configured by the administrator.' })
  }

  try {
    const rpcRes = await fetch(env.SUPABASE_URL + '/rest/v1/rpc/examroom_request', {
      method: 'POST',
      headers: {
        apikey: env.SUPABASE_PUBLISHABLE_KEY,
        Authorization: 'Bearer ' + token,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ operation: 'score_mail_data', payload: { examId } }),
      signal: AbortSignal.timeout(20000),
    })

    const data = await rpcRes.json()
    if (!rpcRes.ok) {
      return res.status(rpcRes.status).json({ error: data.message || 'Examination access denied.' })
    }

    const { exam, classAvg, totalCandidates, candidates } = data
    if (!candidates?.length) {
      return res.json({ sent: 0, failed: 0, message: 'No deliverable candidate submissions found.' })
    }

    const port = Number(env.EMAIL_PORT || 587)
    const transport = nodemailer.createTransport({
      host: env.EMAIL_HOST,
      port,
      secure: port === 465,
      requireTLS: port !== 465,
      auth: { user: env.EMAIL_USER, pass: env.EMAIL_PASS },
      connectionTimeout: 15000,
      greetingTimeout: 15000,
      socketTimeout: 20000,
    })

    let sent = 0
    let failed = 0
    try {
      for (const c of candidates) {
        try {
          const pdfBuf = buildScorePdfBuffer(exam, c, classAvg, totalCandidates)
          const pct = c.total > 0 ? ((c.score / c.total) * 100).toFixed(1) : '0.0'
          const html = `<!doctype html><html><body style="margin:0;background:#f6f6f3;font-family:Arial,sans-serif;color:#34352e"><table role="presentation" width="100%"><tr><td align="center" style="padding:32px 16px"><table role="presentation" width="600" style="max-width:100%;background:#fff;border:1px solid #e4e4df;border-radius:14px"><tr><td style="padding:32px"><p style="font-size:20px;font-weight:bold;margin:0">UnCooked</p><p style="color:#73756c;font-size:12px;letter-spacing:2px">SCORE REPORT</p><h1 style="font-size:24px">${escape(exam.title)}</h1><p>Hello ${escape(c.name)},</p><p>Your official score report is attached as a PDF.</p><table role="presentation" width="100%" style="line-height:1.8;background:#f6f6f3;padding:16px"><tr><td><strong>Your Score</strong></td><td>${c.score} / ${c.total} (${pct}%)</td></tr><tr><td><strong>Class Average</strong></td><td>${classAvg} / ${c.total}</td></tr><tr><td><strong>Percentile</strong></td><td>${c.percentile ?? 0}%</td></tr><tr><td><strong>Rank</strong></td><td>${c.rank} / ${totalCandidates}</td></tr></table></td></tr></table></td></tr></table></body></html>`

          await transport.sendMail({
            from: { name: 'UnCooked', address: env.EMAIL_USER },
            to: { name: c.name, address: c.email },
            subject: `Score report · ${exam.title}`,
            text: `Hello ${c.name},\n\nScore report for ${exam.title}\nYour Score: ${c.score} / ${c.total} (${pct}%)\nClass Average: ${classAvg} / ${c.total}\nPercentile: ${c.percentile ?? 0}%\nRank: ${c.rank} / ${totalCandidates}\n\nYour PDF report is attached.\nUnCooked`,
            html,
            attachments: [
              {
                filename: `score-report-${exam.id.slice(0, 8)}.pdf`,
                content: pdfBuf,
                contentType: 'application/pdf',
              },
            ],
          })
          sent++
        } catch {
          failed++
        }
      }
    } finally {
      transport.close?.()
    }

    return res.json({ sent, failed })
  } catch (err) {
    return res.status(500).json({ error: err.message || 'Could not send score reports.' })
  }
}
